/**
 * External link checker — validates all external URLs in built HTML.
 *
 * Intended to run in GitHub Actions (scheduled weekly). Outputs results
 * to stdout and writes a markdown report to link-check-report.md if
 * any broken links are found (exits with code 1).
 *
 * Usage: node scripts/check-external-links.js
 */

const fs = require('fs');
const path = require('path');
const { JSDOM } = require('jsdom');

const PUBLIC_DIR = path.join(__dirname, '..', 'public');
const REPORT_PATH = path.join(__dirname, '..', 'link-check-report.md');

// Domains to skip (known to block HEAD requests or require auth)
const SKIP_DOMAINS = [
  'facebook.com',
  'www.facebook.com',
  'connect.facebook.net',
  'maps.google.com',
  'www.google.com',
  'fonts.googleapis.com',
  'fonts.gstatic.com',
  'unpkg.com',
];

const TIMEOUT_MS = 10000;
const CONCURRENCY = 5;
const RETRY_COUNT = 1;

function collectHtmlFiles(dir, results = []) {
  if (!fs.existsSync(dir)) return results;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const fullPath = path.join(dir, entry.name);
    if (entry.isDirectory()) {
      collectHtmlFiles(fullPath, results);
    } else if (fullPath.endsWith('.html')) {
      results.push(fullPath);
    }
  }
  return results;
}

function extractExternalLinks(htmlFiles) {
  const linkMap = new Map(); // url -> Set of source files

  for (const file of htmlFiles) {
    const html = fs.readFileSync(file, 'utf8');
    const dom = new JSDOM(html);
    const anchors = dom.window.document.querySelectorAll('a[href]');

    for (const a of anchors) {
      const href = a.getAttribute('href');
      if (!href || !/^https?:\/\//i.test(href)) continue;

      const cleanUrl = href.split('#')[0];
      if (!cleanUrl) continue;

      try {
        const hostname = new URL(cleanUrl).hostname;
        if (SKIP_DOMAINS.some((d) => hostname === d || hostname.endsWith(`.${d}`))) continue;
      } catch {
        continue;
      }

      if (!linkMap.has(cleanUrl)) {
        linkMap.set(cleanUrl, new Set());
      }
      linkMap.get(cleanUrl).add(path.relative(PUBLIC_DIR, file));
    }
  }

  return linkMap;
}

async function checkUrl(url, retries = RETRY_COUNT) {
  for (let attempt = 0; attempt <= retries; attempt++) {
    try {
      const controller = new AbortController();
      const timeout = setTimeout(() => controller.abort(), TIMEOUT_MS);

      const response = await fetch(url, {
        method: 'HEAD',
        signal: controller.signal,
        headers: { 'User-Agent': 'RRROCA-LinkChecker/1.0 (GitHub Actions)' },
        redirect: 'follow',
      });
      clearTimeout(timeout);

      if (response.ok || response.status === 405) {
        // 405 = Method Not Allowed for HEAD, try GET
        if (response.status === 405) {
          const getResp = await fetch(url, {
            method: 'GET',
            signal: AbortSignal.timeout(TIMEOUT_MS),
            headers: { 'User-Agent': 'RRROCA-LinkChecker/1.0 (GitHub Actions)' },
            redirect: 'follow',
          });
          return { url, status: getResp.status, ok: getResp.ok };
        }
        return { url, status: response.status, ok: true };
      }

      if (attempt < retries && response.status >= 500) {
        await new Promise((r) => setTimeout(r, 2000));
        continue;
      }

      return { url, status: response.status, ok: false };
    } catch (err) {
      if (attempt < retries) {
        await new Promise((r) => setTimeout(r, 2000));
        continue;
      }
      return { url, status: 0, ok: false, error: err.message || 'Network error' };
    }
  }
}

async function checkInBatches(urls, concurrency) {
  const results = [];
  const queue = [...urls];

  async function worker() {
    while (queue.length > 0) {
      const url = queue.shift();
      const result = await checkUrl(url);
      results.push(result);
      const symbol = result.ok ? '✓' : '✗';
      const detail = result.error || result.status;
      process.stdout.write(`  ${symbol} [${detail}] ${url}\n`);
    }
  }

  const workers = Array.from({ length: concurrency }, () => worker());
  await Promise.all(workers);
  return results;
}

function generateReport(broken, linkMap) {
  const lines = [
    '# 🔗 Broken External Links Report',
    '',
    `**Date:** ${new Date().toISOString().split('T')[0]}`,
    `**Broken links found:** ${broken.length}`,
    '',
    '## Broken Links',
    '',
    '| URL | Status | Found In |',
    '|-----|--------|----------|',
  ];

  for (const result of broken) {
    const sources = [...linkMap.get(result.url)].slice(0, 3).join(', ');
    const status = result.error || `HTTP ${result.status}`;
    lines.push(`| ${result.url} | ${status} | ${sources} |`);
  }

  lines.push('', '---', '*Generated by `scripts/check-external-links.js`*');
  return lines.join('\n');
}

async function main() {
  console.log('Collecting HTML files...');
  const htmlFiles = collectHtmlFiles(PUBLIC_DIR);
  console.log(`Found ${htmlFiles.length} HTML files`);

  console.log('Extracting external links...');
  const linkMap = extractExternalLinks(htmlFiles);
  console.log(`Found ${linkMap.size} unique external URLs to check\n`);

  console.log('Checking links...');
  const results = await checkInBatches([...linkMap.keys()], CONCURRENCY);

  const broken = results.filter((r) => !r.ok);
  console.log(`\n${'='.repeat(60)}`);
  console.log(`Results: ${results.length - broken.length} OK, ${broken.length} broken`);

  if (broken.length > 0) {
    const report = generateReport(broken, linkMap);
    fs.writeFileSync(REPORT_PATH, report);
    console.log(`\nReport written to ${REPORT_PATH}`);
    process.exit(1);
  }

  console.log('\nAll external links are valid! ✓');
}

main();
